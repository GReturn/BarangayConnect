let currentLocale = localStorage.getItem(STORAGE_KEY) || DEFAULT_LOCALE;

export function getLocale() {
  return currentLocale;
}

export function setLocale(locale) {
  if (LOCALES.includes(locale)) {
    currentLocale = locale;
    localStorage.setItem(STORAGE_KEY, locale);
    // Dispatches a global event for hot reloading
    window.dispatchEvent(new Event('brgyconnect_locale_changed'));
  }
}

export function t(keyPath, params = {}) {
  const parts = keyPath.split('.');
  let translation = translations[currentLocale];

  for (const part of parts) {
    if (translation && translation[part] !== undefined) {
      translation = translation[part];
    } else {
      // Fallback to English if translation is missing
      let engFallback = translations['en'];
      for (const p of parts) {
        if (engFallback && engFallback[p] !== undefined) {
          engFallback = engFallback[p];
        } else {
          engFallback = keyPath;
          break;
        }
      }
      translation = engFallback;
      break;
    }
  }

  // Parameter replacement/interpolation
  let result = typeof translation === 'string' ? translation : keyPath;
  Object.entries(params).forEach(([key, value]) => {
    result = result.replace(new RegExp(`{${key}}`, 'g'), value);
  });

  return result;
}

export default {
  getLocale,
  setLocale,
  t
};
